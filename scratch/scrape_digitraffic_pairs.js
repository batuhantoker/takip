/**
 * TAKIP — which road-weather station Fintraffic pairs with each weathercam (throwaway, like scrape_wydot_sites.js).
 *
 * The weathercam list carries no pairing; each station's detail page has `nearestWeatherStationId`.
 * That is ~815 requests, made one at a time, so the table is generated rather than read live.
 *
 *   node scratch/scrape_digitraffic_pairs.js   -> ../src/lib/feeds/cameras/generated/digitraffic-pairs.generated.ts
 *
 * Pairings change rarely. Rerun when finland.ts logs cameras it has no pairing for.
 */

const fs = require('fs');
const path = require('path');

const BASE = 'https://tie.digitraffic.fi/api/weathercam/v1/stations';
const HEADERS = { 'User-Agent': 'TAKIP/0.1 (+https://github.com/batuhantoker/takip)', 'Digitraffic-User': 'TAKIP/0.1', 'Accept-Encoding': 'gzip' };
const OUT = path.join(__dirname, '..', 'src', 'lib', 'feeds', 'cameras', 'generated', 'digitraffic-pairs.generated.ts');
const GAP_MS = 200;

const sleep = ms => new Promise(r => setTimeout(r, ms));

async function json(url) {
  for (let attempt = 1; attempt <= 3; attempt++) {
    const res = await fetch(url, { headers: HEADERS, signal: AbortSignal.timeout(20000) });
    if (res.ok) return res.json();
    if (res.status !== 429 && res.status < 500) throw new Error(`${url}: HTTP ${res.status}`);
    await sleep(2000 * attempt);
  }
  throw new Error(`${url}: gave up`);
}

(async () => {
  const list = await json(BASE);
  const ids = list.features.map(f => f.id).filter(Boolean).sort();
  const pairs = {};
  let missing = 0;
  for (const [i, id] of ids.entries()) {
    try {
      const detail = await json(`${BASE}/${id}`);
      const ws = detail?.properties?.nearestWeatherStationId;
      if (Number.isInteger(ws)) pairs[id] = ws; else missing++;
    } catch (e) {
      missing++;
      console.warn(String(e));
    }
    if (i % 100 === 99) console.log(`${i + 1}/${ids.length}`);
    await sleep(GAP_MS);
  }
  const body = Object.entries(pairs).map(([cam, ws]) => `  ${cam}: ${ws},`).join('\n');
  fs.writeFileSync(OUT, `// Generated by scratch/scrape_digitraffic_pairs.js on ${new Date().toISOString().slice(0, 10)}. Do not edit.
// Weathercam station → the road-weather station Fintraffic pairs it with (nearestWeatherStationId). CC BY 4.0, Fintraffic.
export const DIGITRAFFIC_PAIRS: Record<string, number> = {
${body}
};
`);
  console.log(`paired ${Object.keys(pairs).length} of ${ids.length}; ${missing} without a pairing -> ${OUT}`);
})();
