/**
 * TAKIP — names for SANRAL i-traffic cameras (throwaway, like scrape_wydot_sites.js).
 *
 * The map's marker list (what i-traffic.ts reads) has ids and coordinates only. Names and metro areas come from
 * the camera list behind www.i-traffic.co.za/cctv: keyless, but it wants a full DataTables body (columns and all;
 * a bare one 302s to /Error) and takes 15–20 s for all ~1,240 rows, too slow for a catalogue region.
 *
 *   node scratch/scrape_itraffic_names.js   -> ../src/lib/cctv/generated/itraffic-names.generated.ts
 *
 * Rerun when i-traffic.ts logs cameras without a name.
 */

const fs = require('fs');
const path = require('path');

const UA = 'TAKIP/0.1 (+https://github.com/batuhantoker/takip)';
const LIST = 'https://www.i-traffic.co.za/List/GetData/Cameras';
const OUT = path.join(__dirname, '..', 'src', 'lib', 'cctv', 'generated', 'itraffic-names.generated.ts');
const PAGE = 100;
// SANRAL's server stalls past three parallel pages.
const WORKERS = 3;

const col = (data, name, searchable, orderable) => ({ data, name, searchable, orderable, search: { value: '', regex: false } });
const body = start => JSON.stringify({
  draw: 1,
  columns: [col('sortId', 'sortId', true, true), col('region', 'region', true, true), col('roadway', 'roadway', true, true), col(3, 'description1', false, true), col(4, '', false, false)],
  order: [{ column: 0, dir: 'desc' }],
  start,
  length: PAGE,
  search: { value: '', regex: false },
});

async function page(start) {
  for (let attempt = 0; ; attempt++) {
    try {
      const res = await fetch(LIST, {
        method: 'POST',
        headers: { 'User-Agent': UA, 'Content-Type': 'application/json', Accept: 'application/json' },
        body: body(start),
        signal: AbortSignal.timeout(60_000),
      });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const json = await res.json();
      if (!Array.isArray(json.data)) throw new Error('no data');
      return json;
    } catch (err) {
      if (attempt >= 2) throw new Error(`page ${start}: ${err.message}`);
    }
  }
}

const tidy = s => (typeof s === 'string' ? s.replace(/\s+/g, ' ').trim() : '');
const quote = s => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

async function main() {
  const first = await page(0);
  const starts = [];
  for (let s = PAGE; s < first.recordsTotal; s += PAGE) starts.push(s);
  const pages = [first];
  let next = 0;
  await Promise.all(Array.from({ length: WORKERS }, async () => {
    while (next < starts.length) pages.push(await page(starts[next++]));
  }));

  const names = new Map();
  for (const row of pages.flatMap(p => p.data)) {
    const id = tidy(row.DT_RowId);
    const name = tidy(row.displayName) || tidy(row.description1);
    if (!/^\d{1,6}--\d{1,3}$/.test(id) || !name) continue;
    names.set(id, [name, tidy(row.cityName) || tidy(row.region)]);
  }
  if (names.size < first.recordsTotal * 0.95) throw new Error(`short read: ${names.size} of ${first.recordsTotal}`);
  console.log(`${names.size} names of ${first.recordsTotal} cameras`);

  const lines = [...names]
    .sort(([a], [b]) => a.localeCompare(b, 'en', { numeric: true }))
    .map(([id, [name, city]]) => `  ${quote(id)}: [${quote(name)}, ${quote(city)}],`);
  fs.writeFileSync(OUT, `/**
 * TAKIP — SANRAL i-traffic camera names (GENERATED by scratch/scrape_itraffic_names.js).
 *
 * Read once from i-traffic's camera list, which is too slow for a catalogue region. A camera missing here
 * keeps a generic name.
 */

/** \`<camera>--<agency>\` → [display name, metro or district]. */
export const ITRAFFIC_NAMES: Record<string, [string, string]> = {
${lines.join('\n')}
};
`);
  console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
}

main().catch(err => { console.error(err); process.exit(1); });
