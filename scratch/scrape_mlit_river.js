/**
 * TAKIP — one-off harvester for MLIT's office river cameras (sys_id 2, ~4,900).
 *
 * The prefecture GeoJSON mlit-river.ts reads lists these cameras, but their still is named
 * `cctv_<office>_<code>.jpg`, which only each camera's own master file carries. River.go.jp asks
 * tools not to poll it, so this runs once and the names are baked into a generated map.
 *
 *   node scratch/scrape_mlit_river.js harvest   -> mlit-river-harvest.json (resumable)
 *   node scratch/scrape_mlit_river.js emit      -> ../src/lib/cctv/generated/mlit-river-cctv.generated.ts
 */

const https = require('https');
const fs = require('fs');
const path = require('path');

const UA = 'TAKIP/0.1 (+https://github.com/batuhantoker/takip)';
const HERE = __dirname;
const HARVEST = path.join(HERE, 'mlit-river-harvest.json');
const OUT = path.join(HERE, '..', 'src', 'lib', 'cctv', 'generated', 'mlit-river-cctv.generated.ts');
const GJSON = 'https://www.river.go.jp/kawabou/file/gjson/scam';
const MASTER = 'https://www.river.go.jp/kawabou/file/files/master/obs/scam';
const PREFS = [102, 103, 104, 105, ...Array.from({ length: 46 }, (_, i) => (i + 2) * 100 + 1)];
const WORKERS = 2;
const PAUSE_MS = 400;
const STILL = /^https:\/\/cam\.river\.go\.jp\/cam\/now\/(cctv_[\w-]+)\.jpg$/;

const sleep = ms => new Promise(r => setTimeout(r, ms));

function getJson(url) {
  return new Promise(resolve => {
    const req = https.get(url, { headers: { 'User-Agent': UA, Accept: 'application/json' }, timeout: 20000 }, res => {
      let data = '';
      res.setEncoding('utf8');
      res.on('data', c => { data += c; });
      res.on('end', () => {
        if (res.statusCode !== 200) return resolve({ status: res.statusCode, json: null });
        try { resolve({ status: 200, json: JSON.parse(data) }); } catch { resolve({ status: 200, json: null }); }
      });
    });
    req.on('timeout', () => req.destroy());
    req.on('error', () => resolve({ status: 0, json: null }));
  });
}

function load() {
  try { return JSON.parse(fs.readFileSync(HARVEST, 'utf8')); } catch { return { ids: [], cameras: {} }; }
}

function save(state) {
  fs.writeFileSync(HARVEST, JSON.stringify(state));
}

async function harvest() {
  const state = load();
  if (!state.ids.length) {
    for (const pref of PREFS) {
      const { json } = await getJson(`${GJSON}/${pref}.json`);
      for (const f of json?.features || []) if (f?.properties?.sys_id === 2) state.ids.push(f.properties.id);
      await sleep(PAUSE_MS);
    }
    state.ids = [...new Set(state.ids)];
    save(state);
    console.log(`listed ${state.ids.length} office cameras`);
  }

  const todo = state.ids.filter(id => !(id in state.cameras));
  console.log(`${todo.length} to fetch, ${state.ids.length - todo.length} already done`);
  let done = 0;
  const worker = async () => {
    while (todo.length) {
      const id = todo.shift();
      const { status, json } = await getJson(`${MASTER}/${id}.json`);
      const o = json?.obsInfo;
      /* Only a definite answer is recorded; a network failure is retried on the next run. */
      if (status === 200 || status === 404) state.cameras[id] = o ? { url: o.currentUrl ?? null, live: o.liveUrl ?? null } : null;
      if (++done % 100 === 0) { save(state); console.log(`${done} fetched`); }
      await sleep(PAUSE_MS);
    }
  };
  await Promise.all(Array.from({ length: WORKERS }, worker));
  save(state);
  console.log(`done: ${Object.keys(state.cameras).length} of ${state.ids.length}`);
}

function emit() {
  const { cameras } = load();
  const entries = [];
  let live = 0;
  for (const [id, cam] of Object.entries(cameras)) {
    const m = STILL.exec(cam?.url ?? '');
    if (m) entries.push([Number(id), m[1]]);
    if (cam?.live) live++;
  }
  entries.sort((a, b) => a[0] - b[0]);
  const body = entries.map(([id, name]) => `  ${id}: '${name}',`).join('\n');
  fs.writeFileSync(OUT, `// Generated by scratch/scrape_mlit_river.js (${new Date().toISOString().slice(0, 10)}). Do not edit.\n`
    + '/** MLIT office river camera id → its still\'s name under cam.river.go.jp/cam/now/. */\n'
    + `export const MLIT_RIVER_CCTV: Record<number, string> = {\n${body}\n};\n`);
  console.log(`emitted ${entries.length} stills (${live} also list a liveUrl)`);
}

const cmd = process.argv[2];
if (cmd === 'harvest') harvest();
else if (cmd === 'emit') emit();
else console.log('usage: node scratch/scrape_mlit_river.js harvest|emit');
