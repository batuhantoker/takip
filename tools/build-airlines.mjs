// Builds src/lib/feeds/aviation/airlines.generated.ts from OpenFlights' airlines.dat (ODbL): every airline with
// both an IATA and an ICAO code, so flight search can read "TK1" as the callsign THY1.
//   node tools/build-airlines.mjs [path/to/airlines.dat]   (downloads it without a path)
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCE = 'https://raw.githubusercontent.com/jpatokal/openflights/master/data/airlines.dat';
const OUT = 'src/lib/feeds/aviation/airlines.generated.ts';

const text = process.argv[2] ? readFileSync(process.argv[2], 'utf8') : await (await fetch(SOURCE)).text();

/** One CSV line: quoted fields, \N for null. */
const fields = line => [...line.matchAll(/"((?:[^"]|"")*)"|\\N|(-?\d+)/g)].map(m => (m[1] ?? m[2] ?? '').replace(/""/g, '"'));

const rows = [];
const seen = new Set();
for (const line of text.split(/\r?\n/)) {
  if (!line.trim()) continue;
  const [, name, , iata, icao, , , active] = fields(line);
  // A 2-character IATA code has at least one letter; all-digit pairs are placeholders.
  if (!/^[A-Z0-9]{2}$/.test(iata ?? '') || !/[A-Z]/.test(iata) || !/^[A-Z]{3}$/.test(icao ?? '')) continue;
  const key = `${iata}${icao}`;
  if (seen.has(key)) continue;
  seen.add(key);
  rows.push({ iata, icao, name: name.trim(), active: active === 'Y' });
}
// Active first: when two airlines share a code, the name shown is the one still flying.
rows.sort((a, b) => Number(b.active) - Number(a.active) || a.iata.localeCompare(b.iata) || a.icao.localeCompare(b.icao));

const body = rows.map(r => `  [${JSON.stringify(r.iata)}, ${JSON.stringify(r.icao)}, ${JSON.stringify(r.name)}],`).join('\n');
writeFileSync(OUT, `// Generated by tools/build-airlines.mjs from OpenFlights airlines.dat (ODbL). Don't edit.

/** [IATA, ICAO, name], the airlines OpenFlights lists as active first. */
export const AIRLINES: readonly (readonly [iata: string, icao: string, name: string])[] = [
${body}
];
`);
console.log(`${OUT}: ${rows.length} airlines`);
