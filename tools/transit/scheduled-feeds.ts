/** A weekday morning on the timetable's own clock, to size a scheduled feed by its peak. */
export function morning(tz: string): Date {
  const at = new Date();
  for (let h = 0; h < 48; h++, at.setTime(at.getTime() + 3_600_000)) {
    const p = Object.fromEntries(new Intl.DateTimeFormat('en-GB', { timeZone: tz, weekday: 'short', hour: '2-digit', hourCycle: 'h23' }).formatToParts(at).map(x => [x.type, x.value]));
    if (p.hour === '08' && !['Sat', 'Sun'].includes(p.weekday)) return at;
  }
  return at;
}

export async function writeSchedules(): Promise<{ feed: TransitFeed; tt: Timetable }[]> {
  const built: { feed: TransitFeed; tt: Timetable }[] = [];
  for (const s of SCHEDULED) {
    const tt = await buildTimetable(s.src).catch(e => {
      console.log(`  no timetable for ${s.id}: ${(e as Error).message}`);
      return null;
    });
    if (!tt) continue;
    const lng = tt.stops.map(x => x[0]), lat = tt.stops.map(x => x[1]);
    built.push({ tt, feed: {
      id: s.id, name: s.name, kind: 'scheduled', url: s.page, license: s.license,
      bbox: pad([Math.min(...lng), Math.min(...lat), Math.max(...lng), Math.max(...lat)]),
      size: scheduledVehicles(tt, morning(tt.tz)).length, modes: sortModes(new Set(tt.routes.map(r => r.mode))),
    } });
  }
  writeFileSync(SCHEDULES_OUT, `// Generated by tools/transit/build-feeds.ts from each system's static GTFS. Do not edit; rerun the tool.
import type { Timetable } from '../placement/scheduled';
import type { TransitFeed } from '../select';

export const SCHEDULED_FEEDS: TransitFeed[] = [
${built.map(b => `  ${JSON.stringify(Object.fromEntries(Object.entries(b.feed).filter(([, v]) => v !== undefined)))},`).join('\n')}
];

export const TIMETABLES: Record<string, Timetable> = {
${built.map(b => `  ${JSON.stringify(b.feed.id)}: ${JSON.stringify(b.tt)},`).join('\n')}
};
`);
  console.log(`wrote ${built.length} timetables (${built.map(b => `${b.feed.id}: ${b.feed.size} trains at a weekday 08:00`).join(', ')}) to ${SCHEDULES_OUT}`);
  return built;
}
