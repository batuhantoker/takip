#!/usr/bin/env node
// Turns Natural Earth's 110m land (public domain) into one SVG path for the share-preview cards.
// Usage: node tools/site/world-land.mjs <ne_110m_land.geojson>
// Download: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
  console.error('usage: node tools/site/world-land.mjs <ne_110m_land.geojson>');
  process.exit(1);
}
const out = fileURLToPath(new URL('../../src/lib/platform/site/world-land.generated.ts', import.meta.url));

// Equirectangular, 1 unit per degree: x = lon + 180, y = 90 - lat.
const fmt = n => (Math.round(n * 2) / 2).toString();
const rings = [];
for (const f of JSON.parse(readFileSync(src, 'utf8')).features) {
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  for (const poly of polys) for (const ring of poly) {
    const pts = [];
    for (const [lon, lat] of ring) {
      const p = `${fmt(lon + 180)} ${fmt(90 - lat)}`;
      if (pts[pts.length - 1] !== p) pts.push(p);
    }
    if (pts.length >= 3) rings.push(`M${pts.join('L')}Z`);
  }
}
const path = rings.join('');
writeFileSync(out, `// Generated by tools/site/world-land.mjs from Natural Earth 110m land (public domain). Do not edit.
// Equirectangular, 1 unit per degree: x = lon + 180, y = 90 - lat (viewBox 0 0 360 180).
export const WORLD_LAND_PATH =
  '${path}';
`);
console.log(`${rings.length} rings, ${path.length} chars → ${out}`);
